def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()

def extract_abstract(chunked_paper: Dict[str, List[str]], *, max_paras: int = 4) -> Optional[str]:
    # 1) Section title match
    for section, paras in chunked_paper.items():
        if re.fullmatch(r"\s*abstract\s*", section, flags=re.IGNORECASE):
            block = "\n\n".join(_norm(p) for p in paras[:max_paras] if p.strip())
            return block or None

    # 2) Inline label: "Abstract—" / "ABSTRACT:"
    label_re = re.compile(r"^\s*abstract\s*[:\-—]\s*", flags=re.IGNORECASE)
    for section, paras in chunked_paper.items():
        for p in paras:
            if label_re.search(p):
                cleaned = label_re.sub("", p, count=1).strip()
                return cleaned or None

    # 3) Before Introduction heading (front matter)
    intro_keys = [k for k in chunked_paper.keys() if re.search(r"\bintroduction\b", k, flags=re.IGNORECASE)]
    if intro_keys:
        keys = list(chunked_paper.keys())
        idx = keys.index(intro_keys[0])
        front_paras: List[str] = []
        for k in keys[:idx]:
            front_paras.extend([_norm(x) for x in chunked_paper.get(k, []) if x.strip()])
        if front_paras:
            return "\n\n".join(front_paras[-max_paras:])

    return None


# ----------------------------
# State + output schema
# ----------------------------
class ThemePick(BaseModel):
    theme: str = Field(..., description="One of the allowed themes.")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence from 0 to 1.")
    rationale: str = Field(..., description="1-3 sentences explaining why this theme fits the abstract.")
    evidence_phrases: List[str] = Field(
        default_factory=list,
        description="Short phrases copied from the abstract that support the choice (max 5).",
        max_length=5,
    )

class GraphState(TypedDict, total=False):
    paper_id: str
    chunked_paper: Dict[str, List[str]]

    abstract: Optional[str]
    theme_pick: Optional[Dict[str, Any]]  # ThemePick.model_dump()


# ----------------------------
# Node 1: get abstract (deterministic)
# ----------------------------
def node_get_abstract(state: GraphState) -> GraphState:
    abstract = extract_abstract(state["chunked_paper"])
    return {**state, "abstract": abstract}


# ----------------------------
# Node 2: classify theme from abstract only (structured output)
# ----------------------------
def node_classify_theme(state: GraphState) -> GraphState:
    abstract = (state.get("abstract") or "").strip()

    # If we truly cannot find it, still classify with "other" at low confidence
    if not abstract:
        return {
            **state,
            "theme_pick": ThemePick(
                theme="other",
                confidence=0.05,
                rationale="No abstract was found; cannot reliably classify theme.",
                evidence_phrases=[],
            ).model_dump(),
        }

    # LLM with strict structured output
    llm = ChatOpenAI(model="gpt-4.1-mini", temperature=0.0)

    # Enforce the enum in-prompt (and validate post-hoc)
    allowed = ", ".join(THEMES)

    system = SystemMessage(
        content=(
            "You classify finance/asset-pricing papers into a predefined theme.\n"
            "You MUST use ONLY the abstract text provided by the user.\n"
            "Pick exactly one theme from the allowed list.\n"
            "If ambiguous, pick the best-fit theme and lower confidence.\n"
            "Return a JSON object that matches the given schema."
        )
    )

    user = HumanMessage(
        content=(
            f"Allowed themes: [{allowed}]\n\n"
            f"ABSTRACT:\n{abstract}"
        )
    )

    # Ask the model for structured output
    pick: ThemePick = llm.with_structured_output(ThemePick).invoke([system, user])

    # Hard validation of theme (guardrail)
    if pick.theme not in THEMES:
        pick.theme = "other"
        pick.confidence = min(pick.confidence, 0.2)
        pick.rationale = f"Model returned an invalid theme; coerced to 'other'. {pick.rationale}"

    # Optional: cap evidence phrases count and keep them short
    pick.evidence_phrases = [p.strip()[:120] for p in pick.evidence_phrases[:5] if p.strip()]

    return {**state, "theme_pick": pick.model_dump()}


# ----------------------------
# Build graph
# ----------------------------
graph = StateGraph(GraphState)
graph.add_node("get_abstract", RunnableLambda(node_get_abstract))
graph.add_node("classify_theme", RunnableLambda(node_classify_theme))

graph.set_entry_point("get_abstract")
graph.add_edge("get_abstract", "classify_theme")
graph.add_edge("classify_theme", END)

theme_graph = graph.compile()


